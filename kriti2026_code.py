def build_nse500_proxy_returns(data_all):
    x = data_all[data_all["in_NSE500"].astype(bool)].copy()
    x.sort_values(["fid","tradedate"], inplace=True)
    x["ret"] = x.groupby("fid")["close"].pct_change()
    # equal-weight across available NSE500 names each day
    bench = x.groupby("tradedate")["ret"].mean().fillna(0.0)
    return bench

def information_ratio(strategy_rets, bench_rets):
    # IR = mean(active)/std(active) * sqrt(252)
    a = (strategy_rets - bench_rets).dropna()
    if len(a) < 2:
        return 0.0
    te = a.std(ddof=1)
    return 0.0 if te <= 1e-12 else np.sqrt(ANNUAL_TRADING_DAYS) * a.mean() / te

def up_down_capture(strategy_rets, bench_rets):
    s = strategy_rets.align(bench_rets, join="inner")[0]
    b = strategy_rets.align(bench_rets, join="inner")[1]
    up = b > 0
    down = b < 0
    up_cap = (s[up].mean() / b[up].mean()) if up.any() and abs(b[up].mean()) > 1e-12 else 0.0
    down_cap = (s[down].mean() / b[down].mean()) if down.any() and abs(b[down].mean()) > 1e-12 else 0.0
    return float(up_cap), float(down_cap)

def rolling_outperformance(strategy_rets, bench_rets, years):
    win = years * ANNUAL_TRADING_DAYS
    s, b = strategy_rets.align(bench_rets, join="inner")
    active = (s - b).fillna(0.0)
    if len(active) < win:
        return None
    roll = active.rolling(win).sum()
    return float(roll.mean()), float(roll.min())

