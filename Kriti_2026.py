def calc_atr(high, low, close, n=21):
    prev = close.shift(1)
    tr = pd.concat([high-low,(high-prev).abs(),(low-prev).abs()],axis=1).max(axis=1)
    return tr.ewm(span=n, adjust=False).mean()

