# INVEST_FRAC CALIBRATION (DF-ONLY, TRAIN/VAL)
# We choose fractions that maximize Sharpe on VAL period (2019) to reduce in-sample bias.
# If VAL has too few days, fallback to TRAIN.
# ----------------------------
def sharpe(sr_rets):
    r = sr_rets.dropna().to_numpy()
    if len(r) < 2:
        return 0.0
    vol = r.std(ddof=1)
    return 0.0 if vol <= 1e-12 else np.sqrt(ANNUAL_TRADING_DAYS) * r.mean() / vol

def pick_best_invest_fracs(panel_df):
    best = {"lc": None, "sm": None, "sharpe": -1e9}
    # decide evaluation window
    eval_start, eval_end = (VAL_START, VAL_END)
    if pd.to_datetime(eval_end) <= pd.to_datetime(eval_start):
        eval_start, eval_end = (TRAIN_START, TRAIN_END)

    for flc in INVEST_FRAC_GRID:
        for fsm in INVEST_FRAC_GRID:
            res = backtest_unified(panel_df, eval_start, eval_end, flc, fsm, lc_thr, sm_thr)
            s = sharpe(res["daily_ret"])
            if s > best["sharpe"]:
                best = {"lc": flc, "sm": fsm, "sharpe": s}
    return best

best = pick_best_invest_fracs(unified)
