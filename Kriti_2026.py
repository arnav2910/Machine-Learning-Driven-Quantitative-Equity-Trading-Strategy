def run_backtest(df, start_date, end_date):
    df_p = df[(df["tradedate"]>=pd.to_datetime(start_date)) &
              (df["tradedate"]<=pd.to_datetime(end_date))].copy()

    dates   = sorted(df_p["tradedate"].unique())
    by_date = {d: g for d, g in df_p.groupby("tradedate")}

    cash         = INITIAL_CAPITAL
    positions    = {}
    equity_curve = []
    trade_log    = []
    pos_counts   = []
    active_model = base_model

    for i in range(len(dates)-1):
        day_T  = dates[i]
        day_T1 = dates[i+1]
        data_T  = by_date.get(day_T)
        data_T1 = by_date.get(day_T1)
        if data_T is None or data_T1 is None: continue

        if day_T in model_store:
            active_model = model_store[day_T]

        row_T  = {r.fid: r for r in data_T.itertuples(index=False)}
        row_T1 = {r.fid: r for r in data_T1.itertuples(index=False)}

        stock_val = sum(
            pos["shares"]*(row_T[f].close if f in row_T else pos["last_close"])
            for f, pos in positions.items())
        for f, pos in positions.items():
            if f in row_T: pos["last_close"] = row_T[f].close
        equity = cash + stock_val
        equity_curve.append({"date":day_T,"equity":equity,"cash":cash})

        held_scores = {}
        for fid, pos in positions.items():
            if fid in row_T:
                st = row_T[fid]
                fv = np.array([[getattr(st,f,0.0) for f in FEATURES]])
                held_scores[fid] = active_model.predict_proba(fv)[0,1]

        live_score_threshold = (
            np.percentile(list(held_scores.values()), RESCORE_PCTILE*100)
            if held_scores else 0.0
        )

        signals_to_sell = []
        for fid, pos in positions.items():
            if fid not in row_T:
                signals_to_sell.append(fid); continue
            st = row_T[fid]

            if st.close > pos["highest_close"]:
                pos["highest_close"] = st.close
                pos["stop_price"]    = st.close - pos["atr"]*STOP_ATR_MULT

            hit_stop     = (pos["hold_days"] >= MIN_HOLD_DAYS and
                            st.close < pos["stop_price"])
            rescore_exit = (pos["hold_days"] >= MIN_HOLD_DAYS and
                            held_scores.get(fid, 1.0) < live_score_threshold)

            if hit_stop or rescore_exit:
                signals_to_sell.append(fid)
            else:
                pos["hold_days"] += 1

        scored = []
        for st in data_T.itertuples(index=False):
            fid = st.fid
            if fid in positions or fid not in row_T1: continue
            fv    = np.array([[getattr(st,f,0.0) for f in FEATURES]])
            score = active_model.predict_proba(fv)[0,1]
            scored.append((fid, score, float(getattr(st,"atr21",1.0))))

        buy_candidates = []
        if scored:
            thr = np.percentile([s[1] for s in scored], (1-TOP_PCTILE)*100)
            buy_candidates = sorted(
                [(f,s,a) for f,s,a in scored if s>=thr],
                key=lambda x: x[1], reverse=True
            )
            open_slots = MAX_HOLDINGS - len(positions) + len(signals_to_sell)
            buy_candidates = buy_candidates[:min(DAILY_BUY_LIMIT, open_slots)]

        for fid in signals_to_sell:
            if fid not in row_T1: continue
            st1      = row_T1[fid]
            ep       = (st1.open+st1.high+st1.low+st1.close)/4.0
            proceeds = positions[fid]["shares"]*ep*(1.0-COST_PER_SIDE)
            cash    += proceeds
            trade_log.append({
                "date":day_T1,"fid":fid,"action":"SELL",
                "shares":positions[fid]["shares"],"price":ep,
                "hold_days":positions[fid]["hold_days"],
                "pnl_pct":(ep/positions[fid]["entry_price"]-1)*100,
            })
            del positions[fid]

        b_nse   = float(data_T["breadth_nse500"].iloc[0])
        b_uni   = float(data_T["breadth_universe"].iloc[0])
        bear    = (b_nse < 0.40) and (b_uni < 0.40)
        eff_min = 0.55 if bear else MIN_EXPOSURE
        eff_max = 0.85 if bear else MAX_EXPOSURE
        target_exp = eff_min + (eff_max - eff_min) * b_uni

        invested = sum(p["shares"]*p["last_close"] for p in positions.values())
        gap      = max(0.0, target_exp * equity - invested)
        avail    = min(gap, cash)

        if buy_candidates and avail > 500:
            inv_atrs  = [1.0/max(a,1e-6) for _,_,a in buy_candidates]
