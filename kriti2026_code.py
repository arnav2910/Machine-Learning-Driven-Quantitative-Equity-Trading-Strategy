def typical_price(o, h, l, c):
    return (o + h + l + c) / 4.0

def ema_causal(x, span):
    return pd.Series(x).ewm(span=span, adjust=False).mean().to_numpy()

def atr(high, low, close, n=21):
    high = np.asarray(high, float)
    low  = np.asarray(low, float)
    close = np.asarray(close, float)
    prev_close = np.roll(close, 1)
    prev_close[0] = close[0]
    tr = np.maximum(high - low, np.maximum(np.abs(high - prev_close), np.abs(low - prev_close)))
    return pd.Series(tr).ewm(span=n, adjust=False).mean().to_numpy()

def supertrend(high, low, close, atr_n=10, mult=3.0):
    high = np.asarray(high, float)
    low  = np.asarray(low, float)
    close = np.asarray(close, float)

    a = atr(high, low, close, n=atr_n)
    hl2 = (high + low) / 2.0
    upperband = hl2 + mult * a
    lowerband = hl2 - mult * a

    st = np.zeros_like(close, dtype=float)
    direction = np.ones_like(close, dtype=int)

    st[0] = upperband[0]
    direction[0] = 1

    for i in range(1, len(close)):
        fub = upperband[i] if (upperband[i] < upperband[i-1] or close[i-1] > upperband[i-1]) else upperband[i-1]
        flb = lowerband[i] if (lowerband[i] > lowerband[i-1] or close[i-1] < lowerband[i-1]) else lowerband[i-1]

        if direction[i-1] == 1:
            direction[i] = -1 if close[i] <= fub else 1
        else:
            direction[i] = 1 if close[i] >= flb else -1

        st[i] = flb if direction[i] == 1 else fub
        upperband[i], lowerband[i] = fub, flb

    return direction.astype(float), st

def monthly_cpr_from_daily(daily_df):
    x = daily_df.copy()
    x["tradedate"] = pd.to_datetime(x["tradedate"])
    x["month"] = x["tradedate"].dt.to_period("M")

    m = x.groupby("month").agg(
        m_high=("high", "max"),
        m_low=("low", "min"),
        m_close=("close", "last"),
    ).reset_index()

    m["pivot"] = (m["m_high"] + m["m_low"] + m["m_close"]) / 3.0
    m["bc"] = (m["m_high"] + m["m_low"]) / 2.0
    m["tc"] = 2.0 * m["pivot"] - m["bc"]

    m[["pivot_prev","bc_prev","tc_prev"]] = m[["pivot","bc","tc"]].shift(1)
    x = x.merge(m[["month","pivot_prev","bc_prev","tc_prev"]], on="month", how="left")
    return x[["pivot_prev","bc_prev","tc_prev"]].to_numpy()

def gaussian_filter_causal(series, passes=6, span=20):
    y = np.asarray(series, dtype=float)
    for _ in range(passes):
        y = ema_causal(y, span=span)
    return y

def find_last_extrema(y):
    y = np.asarray(y, float)
    dy = np.diff(y)
    s = np.sign(dy)
    s[s == 0] = 1
    ds = np.diff(s)
    maxima = np.where(ds < 0)[0] + 1
    minima = np.where(ds > 0)[0] + 1
    extrema = np.sort(np.concatenate([maxima, minima]))
    return extrema, maxima, minima

def regime_from_last4_extrema(smoothed_window):
    y = np.asarray(smoothed_window, float)
    extrema, maxima, minima = find_last_extrema(y)
    if len(extrema) < EXTREMA_NEED:
        return "sideways"
    last_ext = extrema[-EXTREMA_NEED:]
    max_set, min_set = set(maxima), set(minima)
    last_max = [i for i in last_ext if i in max_set]
    last_min = [i for i in last_ext if i in min_set]
    if len(last_max) < 2 or len(last_min) < 2:
        return "sideways"
    max1, max2 = last_max[-2], last_max[-1]
    min1, min2 = last_min[-2], last_min[-1]
    if y[max2] > y[max1] and y[min2] > y[min1]:
        return "up"
    if y[max2] < y[max1] and y[min2] < y[min1]:
        return "down"
    return "sideways"

def compute_regime_per_stock(close_series):
    close = np.asarray(close_series, float)
    sm = gaussian_filter_causal(close, passes=SMOOTH_PASSES, span=20)
    regimes = np.empty(len(close), dtype=object)
    for i in range(len(close)):
        start = max(0, i - REGIME_WINDOW + 1)
        window = sm[start:i+1]
        regimes[i] = regime_from_last4_extrema(window) if len(window) >= 60 else "sideways"
    return regimes, sm

def max_drawdown(equity_curve):
    ec = np.asarray(equity_curve, float)
    peak = np.maximum.accumulate(ec)
    dd = (ec / peak) - 1.0
    return float(dd.min()), dd

def cagr(equity_curve, dates):
    ec = np.asarray(equity_curve, float)
    if len(ec) < 2:
        return 0.0
    start = pd.to_datetime(dates[0])
    end   = pd.to_datetime(dates[-1])
    years = max((end - start).days / 365.25, 1e-9)
    return (ec[-1] / ec[0]) ** (1.0 / years) - 1.0

