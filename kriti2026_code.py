def calibrate_thresholds(train_scored):
    regimes = ["up","down","sideways"]
    thr = {}
    for r in regimes:
        df_r = train_scored[train_scored["regime"].eq(r)].copy()
        if len(df_r) < 2000:
            df_r = train_scored.copy()
        s = df_r["XGy"].to_numpy()
        y = df_r["fwd_ret"].to_numpy()
        pos = (y > 0).astype(int)
        neg = (y < 0).astype(int)

        q = np.linspace(0.50, 0.98, 25)
        buy_cand = np.quantile(s, q)
        sell_cand = np.quantile(s, 1.0 - q)

        best_buy, best_prec = None, -1
        for t in buy_cand:
            m = s >= t
            if m.sum() < 200:
                continue
            prec = pos[m].mean()
            if prec > best_prec:
                best_prec, best_buy = prec, t

        best_sell, best_nprec = None, -1
        for t in sell_cand:
            m = s <= t
            if m.sum() < 200:
                continue
            nprec = neg[m].mean()
            if nprec > best_nprec:
                best_nprec, best_sell = nprec, t

        if best_buy is None:  best_buy = np.quantile(s, 0.85)
        if best_sell is None: best_sell = np.quantile(s, 0.30)
        if best_sell > best_buy:
            best_sell = min(best_buy, np.quantile(s, 0.35))

        thr[r] = {"tBuy": float(best_buy), "tSell": float(best_sell)}
    return thr

