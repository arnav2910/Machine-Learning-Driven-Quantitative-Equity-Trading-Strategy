def metrics(eq_df, trades_df, label, nifty_df=None):
    if eq_df.empty: return {}
    eq_df = eq_df.copy().set_index("date").sort_index()
    eq_df["dr"] = eq_df["equity"].pct_change()
    s, e  = eq_df["equity"].iloc[0], eq_df["equity"].iloc[-1]
    yrs   = max((eq_df.index[-1]-eq_df.index[0]).days/365.25, 1e-9)
    cagr  = (e/s)**(1/yrs)-1
    vol   = eq_df["dr"].std()*np.sqrt(ANNUAL_TRADING_DAYS)
    sharpe= cagr/vol if vol>0 else 0
    rm    = eq_df["equity"].cummax()
    mdd   = ((eq_df["equity"]-rm)/rm).min()
    calmar= cagr/abs(mdd) if mdd!=0 else 0
    neg   = eq_df["dr"][eq_df["dr"]<0]
    sortino = cagr/(neg.std()*np.sqrt(ANNUAL_TRADING_DAYS)) if len(neg)>0 else 0

    if not trades_df.empty and "pnl_pct" in trades_df.columns:
        sells  = trades_df[trades_df["action"]=="SELL"]["pnl_pct"].dropna()
        winrt  = (sells>0).mean() if len(sells)>0 else np.nan
        avg_w  = sells[sells>0].mean() if (sells>0).any() else 0
        avg_l  = sells[sells<0].mean() if (sells<0).any() else 0
        pf     = abs(avg_w/avg_l) if avg_l!=0 else np.nan
    else:
        winrt=avg_w=avg_l=pf=np.nan

    m = dict(label=label,cagr=cagr,vol=vol,sharpe=sharpe,mdd=mdd,
             calmar=calmar,sortino=sortino,winrate=winrt,
             profit_factor=pf,avg_win=avg_w,avg_loss=avg_l)

    if nifty_df is not None and not nifty_df.empty:
        common = eq_df.index.intersection(nifty_df.index)
        if len(common)>20:
            sr = eq_df.loc[common,"dr"].fillna(0)
            br = nifty_df.loc[common,"nifty_ret"].fillna(0)
            ex = sr-br
            ir = ex.mean()/ex.std()*np.sqrt(ANNUAL_TRADING_DAYS) if ex.std()>0 else 0
            up_c  = sr[br>0].mean()/br[br>0].mean() if br[br>0].mean()!=0 else np.nan
            dn_c  = sr[br<0].mean()/br[br<0].mean() if br[br<0].mean()!=0 else np.nan
            bc    = nifty_df.loc[common,"nifty_close"]
            byrs  = (common[-1]-common[0]).days/365.25
            bcagr = (bc.iloc[-1]/bc.iloc[0])**(1/byrs)-1
            m.update(ir=ir,up_capture=up_c,down_capture=dn_c,bench_cagr=bcagr)
            roll = {}
            for w,lbl in [(252,"1yr"),(756,"3yr"),(1260,"5yr")]:
                if len(ex)>w:
                    rs = ex.rolling(w).sum()*(ANNUAL_TRADING_DAYS/w)
                    roll[lbl]={"avg":rs.dropna().mean(),"worst":rs.dropna().min()}
            m["rolling"]=roll
    return m

