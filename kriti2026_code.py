def backtest_unified(panel_df, start_date, end_date, invest_frac_lc, invest_frac_sm, lc_thr, sm_thr):
    dfp = panel_df[(panel_df["tradedate"] >= pd.to_datetime(start_date)) & (panel_df["tradedate"] <= pd.to_datetime(end_date))].copy()
    dfp.sort_values(["tradedate","fid"], inplace=True)

    dates = dfp["tradedate"].drop_duplicates().sort_values().to_list()
    by_date = {d: g for d, g in dfp.groupby("tradedate", sort=False)}

    cash = INITIAL_CAPITAL
    positions = {}  # fid -> position dict
    equity_curve, hold_count = [], []
    daily_ret = []
    trade_log = []
    turnover_value = 0.0

    prev_equity = INITIAL_CAPITAL

    for i in range(len(dates) - 1):
        d0, d1 = dates[i], dates[i+1]
        g0, g1 = by_date.get(d0), by_date.get(d1)
        if g0 is None or g1 is None:
            continue

        row0 = {int(r.fid): r for r in g0.itertuples(index=False)}
        row1 = {int(r.fid): r for r in g1.itertuples(index=False)}

        # ---- Mark-to-market at close of d0
        eq = cash
        for fid, pos in positions.items():
            px = float(row0[fid].close) if fid in row0 else pos["last_close"]
            eq += pos["shares"] * px
        equity_curve.append(eq)
        hold_count.append(len(positions))
        daily_ret.append((eq / prev_equity) - 1.0)
        prev_equity = eq

        # ---- Update last_close for robustness
        for fid, pos in positions.items():
            if fid in row0:
                pos["last_close"] = float(row0[fid].close)

        # ---- Forced exits on d1 (stop / max hold) with bucket-specific stop management
        forced_sells = []
        for fid, pos in list(positions.items()):
            pos["hold_days"] += 1

            if fid not in row1:
                continue

            r1 = row1[fid]
            low1 = float(r1.low)
            close1 = float(r1.close)
            atr1 = float(r1.atr21)

            if pos["bucket"] == "smallmid":
                # breakeven ratchet trigger using entry ATR
                pos["highest_close"] = max(pos["highest_close"], close1)
                if (pos["highest_close"] - pos["entry_px"]) >= (BREAKEVEN_ATR_MULT * pos["entry_atr"]):
                    pos["breakeven_active"] = True

                if pos["breakeven_active"]:
                    trail_stop = pos["highest_close"] - (TRAIL_ATR_MULT * atr1)
                    pos["stop_px"] = max(pos["stop_px"], pos["entry_px"], trail_stop)
                else:
                    pos["stop_px"] = max(pos["stop_px"], pos["entry_px"] - STOP_ATR_MULT * pos["entry_atr"])

            # hard exit
            if pos["hold_days"] >= MAX_HOLD_DAYS or low1 <= pos["stop_px"]:
                forced_sells.append((fid, "forced"))

        # execute forced sells at d1 typical price, net of costs
        for fid, why in forced_sells:
            if fid not in positions or fid not in row1:
                continue
            r1 = row1[fid]
            exec_px = typical_price(float(r1.open), float(r1.high), float(r1.low), float(r1.close))
            net_px = exec_px * (1.0 - COST)
            val = positions[fid]["shares"] * net_px
            cash += val
            turnover_value += (positions[fid]["shares"] * exec_px)  # turnover on gross exec price
            trade_log.append((d1, fid, "SELL", positions[fid]["bucket"], positions[fid]["shares"], exec_px, "forced"))
            del positions[fid]

        # ---- Signal sells on d0, executed on d1
        signal_sells = []
        for fid, pos in list(positions.items()):
            if fid not in row0 or fid not in row1:
                continue
            r0 = row0[fid]
            reg = str(r0.regime)
            thr = lc_thr if pos["bucket"]=="largecap" else sm_thr
            tSell = thr.get(reg, thr["sideways"])["tSell"]

            if float(r0.XGy) <= tSell and pos["hold_days"] >= MIN_HOLD_DAYS:
                signal_sells.append(fid)

        # "minimum 1 holding except cash calls": avoid selling last position if there are no buys queued
        # (unless it was forced already, handled above)
        # We approximate "buys queued" by checking if any candidate exists on d0.
        # We'll compute candidates first, then decide if we allow last sell.
        # So defer execution until after candidate build.

        # ---- Build buy candidates from d0, executed on d1 (bucket-specific thresholds)
        candidates = []
        for r in g0.itertuples(index=False):
            fid = int(r.fid)
            if fid in positions:
                continue
            if fid not in row1:
                continue
            if pd.isna(r.XGy) or pd.isna(r.atr21):
                continue

            bucket = str(r.cap_bucket)
            thr = lc_thr if bucket=="largecap" else sm_thr
            reg = str(r.regime)
            tBuy = thr.get(reg, thr["sideways"])["tBuy"]
            if float(r.XGy) >= tBuy:
                candidates.append((fid, float(r.XGy), float(r.atr21), bucket, reg))

        # now enforce "min holdings" logic for signal sells
        if len(positions) == 1 and len(signal_sells) == 1 and len(candidates) == 0:
            # keep the last position (cash call exception not applicable because we already hold one)
            signal_sells = []

        for fid in signal_sells:
            if fid not in positions or fid not in row1:
                continue
            r1 = row1[fid]
            exec_px = typical_price(float(r1.open), float(r1.high), float(r1.low), float(r1.close))
            net_px = exec_px * (1.0 - COST)
            val = positions[fid]["shares"] * net_px
            cash += val
            turnover_value += (positions[fid]["shares"] * exec_px)
            trade_log.append((d1, fid, "SELL", positions[fid]["bucket"], positions[fid]["shares"], exec_px, "signal"))
            del positions[fid]

        # ---- Buys: budget split by bucket, max holdings cap
        if candidates and len(positions) < MAX_HOLDINGS and cash > 0:
            # cap number of new names so we never exceed MAX_HOLDINGS
            room = MAX_HOLDINGS - len(positions)
            candidates = sorted(candidates, key=lambda x: x[1], reverse=True)[:room]

            # split candidates by bucket
            cand_lc = [c for c in candidates if c[3] == "largecap"]
            cand_sm = [c for c in candidates if c[3] == "smallmid"]

            # allocate separate budgets
            budget_lc = cash * invest_frac_lc
            budget_sm = cash * invest_frac_sm

            def execute_buys(cands, budget, bucket_name):
                nonlocal cash, turnover_value, positions, trade_log
                if not cands or budget <= 0:
                    return
                scores = np.array([max(c[1], 0.0) for c in cands], float)
                ssum = scores.sum()
                if ssum <= 1e-12:
                    return
                for (fid, sc, atr_val, bucket, reg) in cands:
                    r1 = row1[fid]
                    exec_px = typical_price(float(r1.open), float(r1.high), float(r1.low), float(r1.close))
                    gross_px = exec_px * (1.0 + COST)

                    w = max(sc, 0.0) / ssum
                    alloc = budget * w

                    shares = int(alloc // gross_px)
                    if shares <= 0:
                        continue

                    cost_val = shares * gross_px
                    if cost_val > cash:
                        continue

                    cash -= cost_val
                    turnover_value += (shares * exec_px)
                    positions[fid] = {
                        "bucket": bucket,
                        "shares": shares,
                        "entry_px": exec_px,
                        "entry_atr": float(atr_val),
                        "stop_px": exec_px - STOP_ATR_MULT * float(atr_val),
                        "hold_days": 0,
                        "last_close": float(r1.close),
                        # small/mid extras (safe for largecap too)
                        "highest_close": float(r1.close),
                        "breakeven_active": False,
                    }
                    trade_log.append((d1, fid, "BUY", bucket, shares, exec_px, "signal"))

            execute_buys(cand_lc, budget_lc, "largecap")
            execute_buys(cand_sm, budget_sm, "smallmid")

        # enforce MAX_HOLDINGS (hard)
        if len(positions) > MAX_HOLDINGS:
            # should never happen due to room cap; keep as safety
            # if it does, drop lowest XGy names at next day (not ideal)
            pass

    res = {
        "dates": pd.to_datetime(dates[:len(equity_curve)]),
        "equity": np.array(equity_curve, float),
        "daily_ret": pd.Series(daily_ret, index=pd.to_datetime(dates[:len(equity_curve)])),
        "hold_count": pd.Series(hold_count, index=pd.to_datetime(dates[:len(equity_curve)])),
        "turnover_value": float(turnover_value),
        "trade_log": pd.DataFrame(trade_log, columns=["date","fid","side","bucket","shares","exec_px","reason"])
    }
    return res

