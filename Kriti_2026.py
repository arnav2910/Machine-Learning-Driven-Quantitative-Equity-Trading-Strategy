def download_tickers(ticker_list, data_start, data_end):
    frames = []
    failed = []
    for ticker, cap in ticker_list:
        try:
            raw = yf.download(ticker, start=data_start, end=data_end,
                              progress=False, auto_adjust=True)
            if raw.empty or len(raw) < 100:
                failed.append(ticker); continue
            if isinstance(raw.columns, pd.MultiIndex):
                raw.columns = raw.columns.get_level_values(0)
            df = raw[["Open","High","Low","Close","Volume"]].copy()
            df.columns = ["open","high","low","close","volume"]
            df = df.reset_index()
            df.rename(columns={"Date":"tradedate"}, inplace=True)
            df["tradedate"] = pd.to_datetime(df["tradedate"]).dt.tz_localize(None)
            df["fid"]                = ticker
            df["cap_classification"] = cap
            df["in_NSE500"]          = 1 if cap == "largecap" else 0
            df["sector"]             = SECTOR_MAP.get(ticker, "Other")
            df = df.dropna()
            frames.append(df)
        except Exception as e:
            failed.append(ticker)
    if failed:
        print(f"  Skipped {len(failed)} tickers: {failed[:5]}{'...' if len(failed)>5 else ''}")
    return pd.concat(frames, ignore_index=True) if frames else pd.DataFrame()

